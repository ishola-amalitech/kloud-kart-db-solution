-- Phase 1 prepares the stocktake while preserving the imported balances.
-- Run during the checkout maintenance window described in the rollout guide.
-- Availability is an application control: a legacy sale that ignores the flag
-- can still write stock. Pause those sale paths before applying this file.
\set ON_ERROR_STOP on
BEGIN;
-- Keep the rollout from queuing indefinitely behind a long-lived transaction.
SET LOCAL lock_timeout = '5s';

-- Existing products remain available unless their stock needs reconciliation.
ALTER TABLE public.products
    ADD COLUMN is_available boolean NOT NULL DEFAULT true;

-- Preserve the bad balances as evidence and stop flag-aware checkout for
-- these products while the operator verifies physical stock.
UPDATE public.products
SET is_available = false
WHERE stock_quantity < 0;

-- The original import assigned IDs explicitly. Start generated IDs above the
-- imported high-water mark while the table is locked by ALTER TABLE.
ALTER TABLE public.inventory_log
    ALTER COLUMN log_id ADD GENERATED BY DEFAULT AS IDENTITY;

-- The third argument, false, makes the first generated ID equal to the
-- chosen value. BY DEFAULT allows imported IDs; live writers should use the
-- default to avoid colliding with IDs assigned by another session.
SELECT pg_catalog.setval(
    pg_catalog.pg_get_serial_sequence('public.inventory_log', 'log_id'),
    greatest(coalesce(max(log_id), 0)::bigint + 1, 1),
    false
)
FROM public.inventory_log;

-- Operator control for pausing and resuming sales independently of stock.
-- Invoker permissions apply, so deploy it with the intended operator role.
CREATE FUNCTION public.set_product_sale_availability(
    p_product_id integer,
    p_is_available boolean
) RETURNS void
LANGUAGE plpgsql
SET search_path = pg_catalog, public
AS $function$
BEGIN
    IF p_is_available IS NULL THEN
        RAISE EXCEPTION 'An availability value is required';
    END IF;

    -- A product with unresolved or unknown stock cannot be put back on sale.
    UPDATE public.products AS p
    SET is_available = p_is_available
    WHERE p.product_id = p_product_id
      AND (NOT p_is_available OR p.stock_quantity >= 0);

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Product % is missing or has unresolved stock', p_product_id;
    END IF;
END;
$function$;

-- Reconcile one paused product. The expected balance comes from the worklist
-- and the counted balance comes from a verified stocktake.
CREATE FUNCTION public.reconcile_negative_stock(
    p_product_id integer,
    p_expected_stock integer,
    p_counted_stock integer,
    p_reason text
) RETURNS integer
LANGUAGE plpgsql
SET search_path = pg_catalog, public
AS $function$
DECLARE
    v_log_id integer;
BEGIN
    -- Scope this operation to negative balances and require an audit reason.
    IF p_expected_stock IS NULL OR p_expected_stock >= 0
       OR p_counted_stock IS NULL OR p_counted_stock < 0
       OR p_reason IS NULL OR btrim(p_reason) = '' THEN
        RAISE EXCEPTION 'Supply a negative recorded balance, a nonnegative verified count, and a reason';
    END IF;

    -- Check the operator's previously observed balance at write time. If
    -- another writer changed it, review the product and count again.
    UPDATE public.products AS p
    SET stock_quantity = p_counted_stock
    WHERE p.product_id = p_product_id
      AND NOT p.is_available
      AND p.stock_quantity = p_expected_stock;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Product % is missing, available for sale, or its stock changed', p_product_id;
    END IF;

    -- The adjustment and this audit record commit together. Leave the product
    -- paused so resuming sales requires a separate decision.
    INSERT INTO public.inventory_log (product_id, change_qty, reason, created_at, note)
    VALUES (
        p_product_id, p_counted_stock - p_expected_stock, 'correction',
        statement_timestamp() AT TIME ZONE 'UTC',
        format('Reconciled from %s to %s by %s. %s',
               p_expected_stock, p_counted_stock, current_user, btrim(p_reason))
    )
    RETURNING log_id INTO v_log_id;

    -- Return an audit reference the operator can attach to the stocktake.
    RETURN v_log_id;
END;
$function$;

-- Publish the flag, paused products, ID default, and functions together.
COMMIT;
