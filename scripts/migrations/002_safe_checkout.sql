-- Phase 2 installs the stock invariant and safe checkout after reconciliation.
-- Apply only after the negative-stock worklist is empty. This transaction makes
-- the checkout entry point visible together with its supporting schema.
\set ON_ERROR_STOP on
BEGIN;
-- Abort promptly if an existing transaction prevents acquiring a table lock.
SET LOCAL lock_timeout = '5s';

-- Validation fails and rolls back the migration if any negative stock remains.
-- Existing NULL balances stay unknown and cannot pass the checkout stock test.
ALTER TABLE public.products
    ADD CONSTRAINT products_stock_nonnegative CHECK (stock_quantity >= 0);

-- Concurrent checkouts need database-generated IDs. Preserve the imported
-- primary keys and initialize each identity above the existing maximum.
ALTER TABLE public.orders
    ALTER COLUMN order_id ADD GENERATED BY DEFAULT AS IDENTITY;
ALTER TABLE public.order_items
    ALTER COLUMN order_item_id ADD GENERATED BY DEFAULT AS IDENTITY;

SELECT pg_catalog.setval(
    pg_catalog.pg_get_serial_sequence('public.orders', 'order_id'),
    greatest(coalesce(max(order_id), 0)::bigint + 1, 1),
    false
)
FROM public.orders;

SELECT pg_catalog.setval(
    pg_catalog.pg_get_serial_sequence('public.order_items', 'order_item_id'),
    greatest(coalesce(max(order_item_id), 0)::bigint + 1, 1),
    false
)
FROM public.order_items;

-- Past movements have no verified order-item link. New checkout writes one.
-- Check the link at commit so an order item and its log can be removed in
-- either order within one transaction (as in the supplied fixture cleanup).
ALTER TABLE public.inventory_log
    ADD COLUMN order_item_id integer,
    ADD CONSTRAINT inventory_log_order_item_fk
        FOREIGN KEY (order_item_id) REFERENCES public.order_items (order_item_id)
        DEFERRABLE INITIALLY DEFERRED;

-- The partial index supports link lookups and foreign-key checks on item
-- deletion. Historical rows with no known link need no index entry.
CREATE INDEX inventory_log_order_item_idx ON public.inventory_log (order_item_id)
WHERE order_item_id IS NOT NULL;

-- Keep the exact signature and result columns expected by the supplied race
-- harness. The function runs inside the caller's transaction.
CREATE FUNCTION public.place_order(
    p_customer_id bigint,
    p_product_id bigint,
    p_quantity integer
) RETURNS TABLE (success boolean, order_id bigint, message text)
LANGUAGE plpgsql
SET search_path = pg_catalog, public
AS $function$
DECLARE
    v_price numeric;
    v_total numeric;
    v_order_id integer;
    v_order_item_id integer;
    v_ordered_at timestamp := statement_timestamp() AT TIME ZONE 'UTC';
BEGIN
    -- A zero or negative quantity cannot represent a purchase. Check before
    -- touching rows, since subtracting a negative quantity would add stock.
    IF p_quantity IS NULL OR p_quantity <= 0 THEN
        RETURN QUERY SELECT false, NULL::bigint, 'Quantity must be positive'::text;
        RETURN;
    END IF;

    -- Protect the customer row from deletion during checkout. A missing
    -- customer fails before the stock row is updated.
    PERFORM 1 FROM public.customers AS c
    WHERE c.customer_id = p_customer_id
    FOR KEY SHARE;

    IF NOT FOUND THEN
        RETURN QUERY SELECT false, NULL::bigint, 'Customer not found'::text;
        RETURN;
    END IF;

    -- Use READ COMMITTED. If another checkout or pause holds this row, the
    -- UPDATE waits and rechecks these predicates against the committed row.
    -- A separate unlocked stock read could go stale before a later write.
    UPDATE public.products AS p
    SET stock_quantity = p.stock_quantity - p_quantity
    WHERE p.product_id = p_product_id
      AND p.is_available
      AND p.stock_quantity >= p_quantity
      AND p.price >= 0
      AND p.price <> 'NaN'::numeric
    RETURNING p.price INTO v_price;

    -- A skipped update has made no writes. Preserve the harness's expected
    -- out-of-stock wording for an ordinary checkout refusal.
    IF NOT FOUND THEN
        RETURN QUERY SELECT false, NULL::bigint, 'Out of stock or unavailable'::text;
        RETURN;
    END IF;

    -- Use the price from the row claimed by the stock update. The same price
    -- is stored on the line so later product price edits keep history intact.
    v_total := v_price * p_quantity;
    IF v_total >= 10000000000 THEN
        -- Raising an error here undoes the deduction as well. Preserve the
        -- legacy numeric(12,2) limit until prices and totals are migrated.
        RAISE EXCEPTION 'Order total exceeds the supported range';
    END IF;

    -- The caller's transaction covers all four writes. Any failure rolls back
    -- the stock decrement, the order, the line, and the movement together.
    INSERT INTO public.orders AS o (customer_id, order_date, status, total_amount)
    VALUES (p_customer_id, v_ordered_at, 'completed', v_total)
    RETURNING o.order_id INTO v_order_id;

    INSERT INTO public.order_items (order_id, product_id, quantity, unit_price)
    VALUES (v_order_id, p_product_id, p_quantity, v_price)
    RETURNING order_item_id INTO v_order_item_id;

    -- Sales are outward movements. Link the movement to the exact order item
    -- so an operator can trace the deduction back to a purchase.
    INSERT INTO public.inventory_log (product_id, change_qty, reason, created_at, order_item_id)
    VALUES (p_product_id, -p_quantity, 'sale', v_ordered_at, v_order_item_id);

    RETURN QUERY SELECT true, v_order_id::bigint, 'Order placed'::text;
END;
$function$;

COMMIT;
